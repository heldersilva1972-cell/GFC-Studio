// GFC POS Revision: 2.43.79
// In development, always fetch from the network and do not enable caching.
// This is appropriate during development as it avoids complex issues when changing static assets.
self.addEventListener('install', event => event.waitUntil(self.skipWaiting()));
self.addEventListener('activate', event => event.waitUntil(self.clients.claim()));
self.addEventListener('fetch', event => {
    // Explicitly pass through all requests to the network. 
    // This satisfies PWA installability requirements while avoiding potential intercept errors.
    // [FIX] Prevents "TypeError: Failed to convert value to 'Response'" in some browsers.
    if (event.request.method === 'POST') {
        return; // Let POST requests fall through naturally
    }
    event.respondWith(fetch(event.request));
});































































































































































































































